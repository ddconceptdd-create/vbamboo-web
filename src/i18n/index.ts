export const LOCALES = ['vi', 'en'] as const;
export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = 'vi';

export const isLocale = (v: string): v is Locale => (LOCALES as readonly string[]).includes(v);

export type Bi = { vi: string; en: string };
/** Pick the text for a locale, falling back to the other language when one is empty. */
export const t = (b: Bi | null | undefined, locale: Locale): string => {
  if (!b) return '';
  return (b[locale] || b[locale === 'vi' ? 'en' : 'vi'] || '').trim();
};

